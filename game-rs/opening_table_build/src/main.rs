use game_rs::{settings::CELL_COUNT, ai_player::default_ai_pick_move, PackedGameState, location::PackedLocation, Player, location::Location, MoveResult};

pub const OPENING_MOVE: PackedLocation = CELL_COUNT as PackedLocation / 2;

// turn 2, its you turn
#[must_use]
pub fn generate_opening_table_turn_2() -> [PackedLocation; CELL_COUNT] {
	std::array::from_fn(|i| {
		eprintln!("gen 2: {}", i);
		let mut game_state = PackedGameState::new();
		assert_eq!(game_state.make_move(&Location::from_index(i)), MoveResult::Ok);
		let ai_move = default_ai_pick_move(&game_state).picked_move as PackedLocation;
		assert_eq!(game_state.make_move(&Location::from_index(ai_move as usize)), MoveResult::Ok);
		ai_move
	})
}

// turn 3, you have played center
#[must_use]
pub fn generate_opening_table_turn_3() -> [PackedLocation; CELL_COUNT] {
	std::array::from_fn(|i| {
		if i == OPENING_MOVE as usize {
			// this move should not happen. bcz always play center first
			return OPENING_MOVE;
		}

		eprintln!("gen 3: {}", i);
		let mut game_state = PackedGameState::new();
		assert_eq!(game_state.make_move(&Location::from_index(OPENING_MOVE as usize)), MoveResult::Ok);
		assert_eq!(game_state.make_move(&Location::from_index(i)), MoveResult::Ok);
		let ai_move = default_ai_pick_move(&game_state).picked_move as PackedLocation;
		assert_eq!(game_state.make_move(&Location::from_index(ai_move as usize)), MoveResult::Ok);
		ai_move
	})
}

fn main() {
	println!(
"// Generated by `./game-rs/opening_table_build`
// turn 1
pub const OPENING_MOVE: PackedLocation = {:?};
// turn 2
pub const OPENING_TABLE_2: [PackedLocation; CELL_COUNT] = {:?};
// turn 3 (with first being 1)
pub const OPENING_TABLE_3: [PackedLocation; CELL_COUNT] = {:?};
		",
		OPENING_MOVE,
		generate_opening_table_turn_2(),
		generate_opening_table_turn_3()
	);
}
